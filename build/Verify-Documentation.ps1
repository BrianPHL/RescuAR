#requires -Version 7.0
[CmdletBinding()]
param([switch]$UpdateCatalog)

# Static repository checks only. Requires Git and PowerShell 7; no app/network access.
$ErrorActionPreference = 'Stop'
$repositoryRoot = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..'))
$catalogRelativePath = 'docs/catalog.md'
$catalogPath = Join-Path $repositoryRoot $catalogRelativePath
$documentPaths = @(& git -C $repositoryRoot ls-files --cached --others --exclude-standard -- '*.md')
if ($LASTEXITCODE -ne 0) { throw 'Could not enumerate repository documentation with Git.' }
$documentPaths = @(@($documentPaths) + $catalogRelativePath | Sort-Object -Unique)

function Get-DocumentRole([string]$Path) {
    if ($Path -match '(^|/)(AGENTS|GEMINI|CLAUDE)\.md$' -or
        $Path -eq '.github/copilot-instructions.md') { return 'Agent entry points' }
    if ($Path -in @('docs/README.md', 'docs/catalog.md', 'docs/changes/README.md',
            'docs/merge-analysis/README.md', 'RescuAR.Admin/prep_api/validation/README.md')) {
        return 'Indexes and navigation'
    }
    if ($Path -like 'docs/changes/*') { return 'Change records' }
    if ($Path -match '^(AR_|ARCORE_(BATCH_|TIP_))[^/]*\.md$' -or
        $Path -like 'docs/merge-analysis/*' -or
        $Path -match '^docs/field-testing/\d{4}-\d{2}-\d{2}-' -or
        $Path -match '^RescuAR\.Admin/(APPLY_PATCH|PATCH_README|README_PATCH)\.md$' -or
        $Path -like 'RescuAR.Admin/prep_api/validation/legacy/*' -or
        $Path -like 'RescuAR.Admin/scraper/data/historical/pagasa/*') {
        return 'Historical evidence'
    }
    if ($Path -like 'RescuAR.Admin/prep_api/validation/*' -or
        $Path -like 'RescuAR.Admin/scraper/data/historical/*') {
        return 'Research and data references'
    }
    return 'Project guides'
}

$documents = @(
    foreach ($relativePath in $documentPaths) {
        $fullPath = Join-Path $repositoryRoot $relativePath
        if ($relativePath -eq $catalogRelativePath) {
            $title = 'Documentation catalog'
        } elseif (Test-Path -LiteralPath $fullPath -PathType Leaf) {
            $heading = [IO.File]::ReadLines($fullPath) | Where-Object { $_ -match '^# ' } |
                Select-Object -First 1
            $title = if ($heading) { $heading.Substring(2).Trim() } else { [IO.Path]::GetFileName($relativePath) }
        } else {
            throw "Document listed by Git is absent: $relativePath"
        }
        [pscustomobject]@{ Path = $relativePath; Title = $title; Role = Get-DocumentRole $relativePath }
    }
)

$catalog = [Text.StringBuilder]::new()
[void]$catalog.AppendLine('# Documentation catalog')
[void]$catalog.AppendLine()
[void]$catalog.AppendLine('Generated by `build/Verify-Documentation.ps1 -UpdateCatalog`; do not edit this list manually.')
[void]$catalog.AppendLine("Inventories $($documents.Count) repository Markdown files, including nonignored new files.")
[void]$catalog.AppendLine('Use the [task index](README.md) first. A catalog entry is discovery metadata, not proof of current behavior or permission to execute old commands.')
[void]$catalog.AppendLine()
$roles = @('Agent entry points', 'Indexes and navigation', 'Project guides',
    'Research and data references', 'Historical evidence', 'Change records')
foreach ($role in $roles) {
    [void]$catalog.AppendLine("## $role")
    [void]$catalog.AppendLine()
    [void]$catalog.AppendLine('| Document | Repository path |')
    [void]$catalog.AppendLine('| --- | --- |')
    foreach ($document in @($documents | Where-Object Role -eq $role | Sort-Object Path)) {
        $label = $document.Title.Replace('|', '\|').Replace('[', '\[').Replace(']', '\]')
        $target = '../' + (($document.Path -split '/' | ForEach-Object { [uri]::EscapeDataString($_) }) -join '/')
        [void]$catalog.AppendLine(('| [{0}]({1}) | `{2}` |' -f $label, $target, $document.Path))
    }
    [void]$catalog.AppendLine()
}
[void]$catalog.AppendLine('## Other reference assets')
[void]$catalog.AppendLine()
[void]$catalog.AppendLine('- [Original UI screenshot](design/reference/rescuar-ui-reference.png): appearance reference; see [provenance and scope](design/README.md).')
[void]$catalog.AppendLine('- [Packaged Marikina DRRMO preparedness PDF](../RescuAR.MAUI/Resources/Raw/MarikinaDRRMO_PreparednessProtocol.pdf): packaged reference material, not agent instructions or newly verified policy.')
$expectedCatalog = $catalog.ToString()
$normalizeNewlines = { param([string]$Value) $Value.Replace("`r`n", "`n") }
if ($UpdateCatalog) {
    [IO.File]::WriteAllText($catalogPath, $expectedCatalog, [Text.UTF8Encoding]::new($false))
} elseif (-not (Test-Path -LiteralPath $catalogPath) -or
    (& $normalizeNewlines ([IO.File]::ReadAllText($catalogPath))) -cne (& $normalizeNewlines $expectedCatalog)) {
    throw 'Documentation catalog is missing/stale. Run ./build/Verify-Documentation.ps1 -UpdateCatalog.'
}

$errors = [Collections.Generic.List[string]]::new()
$localLinks = 0
function Hide-MarkdownCode([string]$Content) {
    # Preserve offsets/newlines so literal syntax examples are not treated as links.
    $mask = { param($match) [regex]::Replace($match.Value, '[^\r\n]', ' ') }
    $masked = [regex]::Replace($Content,
        '(?ms)^ {0,3}(`{3,}|~{3,})[^\r\n]*\r?\n.*?^ {0,3}\1[ \t]*(?:\r?\n|$)', $mask)
    return [regex]::Replace($masked, '(?s)(`+)(.+?)\1', $mask)
}
foreach ($document in $documents) {
    $fullPath = Join-Path $repositoryRoot $document.Path
    $content = [IO.File]::ReadAllText($fullPath)
    $searchContent = Hide-MarkdownCode $content
    foreach ($match in [regex]::Matches($searchContent, '!?\[[^\]\r\n]*\]\(([^)\r\n]+)\)')) {
        $target = ($match.Groups[1].Value -replace '\s+".*$', '').Trim('<', '>', ' ')
        if ($target -match '^[a-zA-Z][a-zA-Z0-9+.-]*:' -or $target.StartsWith('#')) { continue }
        $targetPath = [uri]::UnescapeDataString(($target -split '[#?]')[0])
        if (-not $targetPath) { continue }
        $localLinks++
        $basePath = if ($targetPath.StartsWith('/')) { $repositoryRoot } else { [IO.Path]::GetDirectoryName($fullPath) }
        $resolved = [IO.Path]::GetFullPath((Join-Path $basePath $targetPath.TrimStart('/')))
        if (-not (Test-Path -LiteralPath $resolved)) {
            $line = ($content.Substring(0, $match.Index) -split "`n").Count
            $errors.Add("$($document.Path):$line -> $target")
        }
    }
}

foreach ($entryName in @('GEMINI.md', 'CLAUDE.md')) {
    $entryPath = Join-Path $repositoryRoot $entryName
    if (-not (Test-Path -LiteralPath $entryPath)) {
        $errors.Add("Missing agent entry: $entryName")
        continue
    }
    $imports = @([regex]::Matches([IO.File]::ReadAllText($entryPath), '(?m)^@([^\r\n]+)\r?$'))
    if ($imports.Count -ne 1 -or $imports[0].Groups[1].Value -notin @('AGENTS.md', './AGENTS.md')) {
        $errors.Add("$entryName must import only the shared root AGENTS.md on its own line.")
    }
}
$copilotPath = Join-Path $repositoryRoot '.github/copilot-instructions.md'
if (-not (Test-Path -LiteralPath $copilotPath) -or
    [IO.File]::ReadAllText($copilotPath) -notmatch '\]\(\.\./AGENTS\.md\)') {
    $errors.Add('Copilot entry must point to root AGENTS.md.')
}
if ($errors.Count) {
    $errors | ForEach-Object { Write-Output $_ }
    throw "$($errors.Count) documentation issue(s) found."
}
Write-Output "Documentation: $($documents.Count) Markdown files; $localLinks local inline links; no missing targets."
Write-Output 'Catalog current; Gemini/Claude imports and Copilot policy pointer valid.'
Write-Output 'Scope: static file checks; external URLs, heading anchors and agent/application runtime behavior not tested.'
